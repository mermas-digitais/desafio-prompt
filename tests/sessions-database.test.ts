import assert from 'node:assert/strict';
import { test } from 'node:test';
import crypto from 'node:crypto';
import { AppDatabase } from '../src/server/db/index.js';

test('sessions preserve room profiles; participation is globally exclusive and releases are fenced', async () => {
  const db = new AppDatabase({ localFile: null });
  await db.createRoom('A', 'A'); await db.createRoom('B', 'B');
  const profile = await db.upsertPlayer({ roomCode: 'A', deviceId: 'one', nickname: 'One', avatar: 'ia' });
  const a = crypto.randomUUID(), b = crypto.randomUUID();
  await db.createGameSession({ id: a, roomCode: 'A', name: 'TV A', createdBy: null });
  await db.createGameSession({ id: b, roomCode: 'B', name: 'TV B', createdBy: null });
  const claim = { id: crypto.randomUUID(), deviceId: 'one', profileId: profile.id, sessionId: a, roundToken: 'round-a' };
  assert.equal(await db.acquireParticipation(claim), true);
  assert.equal(await db.acquireParticipation({ ...claim, id: crypto.randomUUID(), sessionId: b }), false);
  assert.equal((await db.getParticipation('one'))?.id, claim.id);
  await db.releaseParticipation({ ...claim, roundToken: 'old-round' });
  assert.ok(await db.getParticipation('one'));
  await db.releaseParticipation(claim);
  const next = { ...claim, id: crypto.randomUUID(), roundToken: 'next-round' };
  assert.equal(await db.acquireParticipation(next), true);
  await db.releaseParticipation(claim);
  assert.equal((await db.getParticipation('one'))?.id, next.id);
  await db.finishGameSession(a);
  assert.equal(await db.getParticipation('one'), null);
  assert.equal((await db.getGameSessions()).find((session) => session.id === a)?.status, 'ended');
  assert.equal((await db.findPlayerByDeviceId('one', 'A'))?.id, profile.id);
});

test('local session writes and restart recovery roll back on persistence failure', async () => {
  const db = new AppDatabase({ localFile: null });
  await db.createRoom('A', 'A');
  const profile = await db.upsertPlayer({ roomCode: 'A', deviceId: 'one', nickname: 'One', avatar: 'ia' });
  const session = { id: crypto.randomUUID(), roomCode: 'A', name: 'TV', createdBy: null };
  const originalSave = (db as any).saveLocalStore;
  const fail = () => { throw new Error('disk full'); };
  (db as any).saveLocalStore = fail;
  await assert.rejects(db.createGameSession(session), /disk full/);
  assert.deepEqual(await db.getGameSessions(), []);
  (db as any).saveLocalStore = originalSave;
  await db.createGameSession(session);
  const claim = { id: crypto.randomUUID(), deviceId: 'one', profileId: profile.id, sessionId: session.id, roundToken: 'round' };
  (db as any).saveLocalStore = fail;
  await assert.rejects(db.acquireParticipation(claim), /disk full/);
  assert.equal(await db.getParticipation('one'), null);
  (db as any).saveLocalStore = originalSave;
  await db.acquireParticipation(claim);
  (db as any).saveLocalStore = fail;
  await assert.rejects(db.releaseParticipation(claim), /disk full/);
  await assert.rejects(db.finishGameSession(session.id), /disk full/);
  await assert.rejects(db.startGameRuntime(() => {}), /disk full/);
  assert.equal((await db.getParticipation('one'))?.id, claim.id);
  assert.equal((await db.getGameSessions())[0].status, 'active');
  (db as any).saveLocalStore = originalSave;
  await db.startGameRuntime(() => {});
  assert.equal((await db.getGameSessions())[0].status, 'interrupted');
  assert.equal(await db.getParticipation('one'), null);
  assert.equal((await db.findPlayerByDeviceId('one', 'A'))?.id, profile.id);
});
